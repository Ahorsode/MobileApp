import 'package:flutter/material.dart';
import 'package:connectivity_plus/connectivity_plus.dart';
import '../services/sync_service.dart';
import '../services/order_service.dart';
import '../models/order_model.dart';
import '../models/cart_item.dart';

class CheckoutViewModel extends ChangeNotifier {
  final OrderService _orderService = OrderService();
  final SyncService _syncService = SyncService();

  bool _isLoading = false;
  String _errorMessage = '';

  bool get isLoading => _isLoading;
  String get errorMessage => _errorMessage;

  Future<bool> processCheckout(String userId, List<CartItem> cartItems, double totalAmount, String cafeteria) async {
    if (cartItems.isEmpty) return false;

    _setLoading(true);
    _errorMessage = '';

    try {
      final connectivity = await Connectivity().checkConnectivity();
      if (connectivity.any((r) => r == ConnectivityResult.none)) {
        // Offline: Queue order
        await _syncService.queueOrder(userId, cartItems, totalAmount, cafeteria);
        _setLoading(false);
        return true; // We return true but inform UI it's queued
      }

      // Online: Submit directly
      final order = OrderModel(
        id: '', // Will be generated by Firestore
        items: cartItems,
        totalAmount: totalAmount,
        status: 'pending',
        timestamp: DateTime.now(),
        cafeteria: cafeteria,
      );

      await _orderService.placeOrder(userId, order);
      _setLoading(false);
      return true; // Success
    } catch (e) {
      _errorMessage = e.toString().contains('Exception:') 
        ? e.toString().split('Exception: ').last 
        : "Checkout failed: ${e.toString()}";
      _setLoading(false);
      return false; // Failure
    }
  }

  void _setLoading(bool value) {
    _isLoading = value;
    notifyListeners();
  }
}
